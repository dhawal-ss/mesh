use std::{fs, path::PathBuf};

use mesh_lib::backend::{
    BackendCapabilities, BackendKind, BackendStatus, CommunityModerationResult, CustomEmoji,
    MatrixNotification, MatrixQueuedMessageState, MatrixQueuedMessageUpdate,
    MatrixRoomNotificationMode, MatrixRoomPins, MatrixRoomPinsUpdate, MatrixRtcJoinResult,
    MatrixRtcMediaKey, MatrixRtcMediaKeyFailure, MatrixRtcMediaKeyLease, MatrixRtcMediaKeyPause,
    MatrixRtcMember, MatrixRtcMembershipUpdate, MatrixUnreadUpdate, ModerationAuditEntry,
    ModerationRoomOutcome, NotificationPresentationContext, UserPreferences, VoiceProvider,
    VoiceServiceAvailability, VoiceServiceStatus,
};
use mesh_lib::types::{
    community::{ChannelDto, CommunityDto},
    dm::{DirectMessageDto, DmConversationDto},
    identity::IdentityDto,
    message::{AttachmentDto, AttachmentThumbnailDto, MessageDto},
    peer::{NetworkStatusDto, PeerDto},
};
use ts_rs::TS;

const HEADER: &str = r#"// This file is generated by `npm run generate:ipc-types`.
// Do not edit it by hand. Change the Rust DTO and regenerate instead.

"#;

fn declaration<T: TS>() -> String {
    let declaration = T::decl()
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    format!("export {declaration}\n\n")
}

fn generated_contract() -> String {
    let mut output = String::from(HEADER);
    output.push_str(&declaration::<BackendKind>());
    output.push_str(&declaration::<VoiceProvider>());
    output.push_str(&declaration::<VoiceServiceAvailability>());
    output.push_str(&declaration::<VoiceServiceStatus>());
    output.push_str(&declaration::<BackendCapabilities>());
    output.push_str(&declaration::<BackendStatus>());
    output.push_str(&declaration::<MatrixNotification>());
    output.push_str(&declaration::<MatrixUnreadUpdate>());
    output.push_str(&declaration::<MatrixQueuedMessageState>());
    output.push_str(&declaration::<MatrixQueuedMessageUpdate>());
    output.push_str(&declaration::<MatrixRoomNotificationMode>());
    output.push_str(&declaration::<MatrixRoomPins>());
    output.push_str(&declaration::<MatrixRoomPinsUpdate>());
    output.push_str(&declaration::<MatrixRtcMember>());
    output.push_str(&declaration::<MatrixRtcMembershipUpdate>());
    output.push_str(&declaration::<MatrixRtcMediaKey>());
    output.push_str(&declaration::<MatrixRtcMediaKeyFailure>());
    output.push_str(&declaration::<MatrixRtcMediaKeyPause>());
    output.push_str(&declaration::<MatrixRtcMediaKeyLease>());
    output.push_str(&declaration::<MatrixRtcJoinResult>());
    output.push_str(&declaration::<NotificationPresentationContext>());
    output.push_str(&declaration::<UserPreferences>());
    output.push_str(&declaration::<CustomEmoji>());
    output.push_str(&declaration::<ModerationRoomOutcome>());
    output.push_str(&declaration::<ModerationAuditEntry>());
    output.push_str(&declaration::<CommunityModerationResult>());
    output.push_str(&declaration::<IdentityDto>());
    output.push_str(&declaration::<CommunityDto>());
    output.push_str(&declaration::<ChannelDto>());
    output.push_str(&declaration::<AttachmentThumbnailDto>());
    output.push_str(&declaration::<AttachmentDto>());
    output.push_str(&declaration::<MessageDto>());
    output.push_str(&declaration::<DmConversationDto>());
    output.push_str(&declaration::<DirectMessageDto>());
    output.push_str(&declaration::<PeerDto>());
    output.push_str(&declaration::<NetworkStatusDto>());
    output.truncate(output.trim_end().len());
    output.push('\n');
    output
}

fn output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("src")
        .join("types")
        .join("ipc.generated.ts")
}

fn main() {
    let path = output_path();
    fs::write(&path, generated_contract())
        .unwrap_or_else(|error| panic!("failed to write {}: {error}", path.display()));
    println!("generated {}", path.display());
}

#[cfg(test)]
mod tests {
    use super::{generated_contract, output_path};

    #[test]
    fn checked_in_contract_matches_rust_dtos() {
        let path = output_path();
        let checked_in = std::fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("failed to read {}: {error}", path.display()));
        assert_eq!(
            checked_in,
            generated_contract(),
            "{} is stale; run `npm run generate:ipc-types`",
            path.display()
        );
    }
}
