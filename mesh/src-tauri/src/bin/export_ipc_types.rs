fn output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("src")
        .join("types")
        .join("ipc.generated.ts")
}

fn main() {
    let path = output_path();
    fs::write(&path, generated_contract())
        .unwrap_or_else(|error| panic!("failed to write {}: {error}", path.display()));
    println!("generated {}", path.display());
}

#[cfg(test)]
mod tests {
    use super::{generated_contract, output_path};
    use std::path::{Path, PathBuf};

    #[test]
    fn checked_in_contract_matches_rust_dtos() {
        let path = output_path();
        let checked_in = std::fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("failed to read {}: {error}", path.display()));
        assert_eq!(
            checked_in,
            generated_contract(),
            "{} is stale; run `npm run generate:ipc-types`",
            path.display()
        );
    }

    /// Every `.rs` file in the crate, so the scan below cannot miss a DTO by
    /// looking in the wrong module.
    fn rust_sources(directory: &Path, files: &mut Vec<PathBuf>) {
        let entries = std::fs::read_dir(directory)
            .unwrap_or_else(|error| panic!("failed to read {}: {error}", directory.display()));
        for entry in entries {
            let path = entry.expect("failed to read a directory entry").path();
            if path.is_dir() {
                rust_sources(&path, files);
            } else if path.extension().is_some_and(|extension| extension == "rs") {
                files.push(path);
            }
        }
    }

    /// Names of the types that derive `ts_rs::TS`, read out of the crate's own
    /// source rather than from a list someone has to remember to update.
    ///
    /// Production items only: everything from the first `#[cfg(test)]` onwards
    /// is dropped, the same way the other source-shape tests in this crate read
    /// implementations without their test modules.
    fn types_deriving_ts() -> Vec<String> {
        let mut files = Vec::new();
        rust_sources(
            &PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src"),
            &mut files,
        );
        let mut names = Vec::new();
        for file in files {
            let source = std::fs::read_to_string(&file)
                .unwrap_or_else(|error| panic!("failed to read {}: {error}", file.display()));
            let implementation = source.split("#[cfg(test)]").next().unwrap_or_default();
            let mut derives_ts = false;
            let mut derive_list = String::new();
            let mut inside_derive = false;
            for line in implementation.lines() {
                let line = line.trim();
                if inside_derive || line.starts_with("#[derive(") {
                    derive_list.push_str(line);
                    inside_derive = !line.ends_with(")]");
                    if inside_derive {
                        continue;
                    }
                    derives_ts = derive_list
                        .split(|character: char| !character.is_alphanumeric() && character != '_')
                        .any(|token| token == "TS");
                    derive_list.clear();
                    continue;
                }
                if !derives_ts {
                    continue;
                }
                // Attributes, doc comments and blank lines may sit between a
                // derive and the item it belongs to.
                if line.is_empty() || line.starts_with("#[") || line.starts_with("//") {
                    continue;
                }
                // Any visibility, including `pub(crate)`. Missing one would drop
                // a DTO out of this scan without anything saying so, which is
                // the failure this test exists to make impossible.
                let declaration = match line.strip_prefix("pub") {
                    Some(rest) => rest.trim_start_matches(|c: char| c != ' ').trim_start(),
                    None => line,
                };
                let name = declaration
                    .strip_prefix("struct ")
                    .or_else(|| declaration.strip_prefix("enum "))
                    .map(|rest| {
                        rest.split(|character: char| {
                            !character.is_alphanumeric() && character != '_'
                        })
                        .next()
                        .unwrap_or_default()
                    });
                if let Some(name) = name {
                    assert!(!name.is_empty(), "unnamed item in {}", file.display());
                    names.push(name.to_owned());
                }
                derives_ts = false;
            }
        }
        names.sort();
        names.dedup();
        names
    }

    /// The exporter is a hand-written list of `declaration::<T>()` calls, so a
    /// DTO can derive `TS` and still never reach the renderer's contract. That
    /// is not a loud failure: the type simply is not there, the renderer keeps
    /// its own hand-written copy of the shape, and the two drift apart until a
    /// field goes missing in a way nothing checks.
    ///
    /// What this does not cover, so nobody reads more into a green run than it
    /// earns: a type that crosses IPC without deriving `TS` at all is invisible
    /// here. Roughly thirty command return types are in that position, each
    /// mirrored by hand in the renderer. Deciding whether a given one belongs in
    /// the contract needs a look at the type, not a scan, because some of those
    /// renderer types deliberately span both backends and are wider than either
    /// Rust struct.
    #[test]
    fn every_type_deriving_ts_reaches_the_generated_contract() {
        let exporter = include_str!("export_ipc_types.rs");
        let contract = generated_contract();
        let scanned = types_deriving_ts();
        // Measured against the exporter rather than a constant. Every
        // declaration below needs the derive to compile, so finding fewer types
        // than are declared means the scan has stopped recognising some item
        // shape and is no longer checking what it claims to. A new visibility or
        // attribute form trips this instead of quietly shrinking coverage.
        let declared = exporter
            .split("#[cfg(test)]")
            .next()
            .unwrap_or_default()
            .matches("declaration::<")
            .count();
        assert!(
            scanned.len() >= declared,
            "the source scan found {} types deriving TS against {declared} declarations in the \
             exporter, so it is no longer reading every item in this crate",
            scanned.len()
        );
        let unexported: Vec<&String> = scanned
            .iter()
            .filter(|name| !exporter.contains(&format!("declaration::<{name}>()")))
            .collect();
        assert!(
            unexported.is_empty(),
            "{unexported:?} derive ts_rs::TS without a declaration in generated_contract. Add one, \
             or drop the derive if the type does not cross IPC."
        );
        for name in &scanned {
            assert!(
                contract.contains(&format!("export type {name} =")),
                "{name} is listed in generated_contract but missing from its output"
            );
        }
    }
}
