import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const projectRoot = resolve(scriptDirectory, '..')
const packageLock = JSON.parse(await readFile(resolve(projectRoot, 'package-lock.json'), 'utf8'))

const jsPackages = []
for (const [relativePath, lockEntry] of Object.entries(packageLock.packages ?? {})) {
  if (!relativePath || !relativePath.includes('node_modules/')) continue
  const manifestPath = resolve(projectRoot, relativePath, 'package.json')
  try {
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
    jsPackages.push({
      name: manifest.name ?? relativePath.split('node_modules/').at(-1),
      version: manifest.version ?? lockEntry.version ?? 'unknown',
      license: normalizeLicense(manifest.license ?? manifest.licenses),
      source: normalizeSource(manifest.repository, manifest.homepage),
    })
  } catch {
    jsPackages.push({
      name: relativePath.split('node_modules/').at(-1),
      version: lockEntry.version ?? 'unknown',
      license: 'UNKNOWN - REVIEW REQUIRED',
      source: normalizeSource(lockEntry.resolved),
    })
  }
}

const cargoMetadata = JSON.parse(execFileSync('cargo', [
  'metadata',
  '--format-version', '1',
  '--locked',
  '--manifest-path', resolve(projectRoot, 'src-tauri', 'Cargo.toml'),
], { cwd: projectRoot, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }))
const rustPackages = cargoMetadata.packages
  .filter((dependency) => dependency.name !== 'mesh')
  .map((dependency) => ({
    name: dependency.name,
    version: dependency.version,
    license: dependency.license ?? 'UNKNOWN - REVIEW REQUIRED',
    source: dependency.repository ?? dependency.homepage ?? dependency.source ?? '',
  }))

const uniqueSorted = (packages) => [...new Map(
  packages.map((dependency) => [
    `${dependency.name}\u0000${dependency.version}\u0000${dependency.license}`,
    dependency,
  ]),
).values()].sort((left, right) => (
  left.name.localeCompare(right.name) || left.version.localeCompare(right.version)
))

const javascript = uniqueSorted(jsPackages)
const rust = uniqueSorted(rustPackages)
const unknown = [...javascript, ...rust].filter((dependency) => dependency.license.includes('UNKNOWN'))
const table = (packages) => packages
  .map((dependency) => `| ${escapeCell(dependency.name)} | ${escapeCell(dependency.version)} | ${escapeCell(dependency.license)} | ${escapeCell(dependency.source)} |`)
  .join('\n')

const document = `# Mesh third-party notices

Generated by \`npm run generate:third-party-notices\` from the locked JavaScript
and Rust dependency graphs. Regenerate this file on every release candidate.
This inventory does not replace review of the referenced license texts, SBOM,
source-offer obligations, trademarks, or platform redistributables.

- JavaScript packages: ${javascript.length}
- Rust packages: ${rust.length}
- Entries requiring license review: ${unknown.length}

Any \`UNKNOWN - REVIEW REQUIRED\` entry is a release blocker. Legal approval of
the exact candidate remains external acceptance evidence and must not be inferred
from this generated inventory.

## JavaScript dependencies

| Package | Version | License | Source |
| --- | --- | --- | --- |
${table(javascript)}

## Rust dependencies

| Package | Version | License | Source |
| --- | --- | --- | --- |
${table(rust)}
`

await writeFile(resolve(projectRoot, 'THIRD_PARTY_NOTICES.md'), document, 'utf8')
console.log(`Wrote THIRD_PARTY_NOTICES.md with ${javascript.length + rust.length} entries (${unknown.length} requiring review).`)

function normalizeLicense(value) {
  if (typeof value === 'string' && value.trim()) return value.trim()
  if (Array.isArray(value)) {
    const licenses = value.map((entry) => (
      typeof entry === 'string' ? entry : entry?.type
    )).filter(Boolean)
    if (licenses.length > 0) return licenses.join(' OR ')
  }
  return 'UNKNOWN - REVIEW REQUIRED'
}

function normalizeSource(repository, homepage = '') {
  if (typeof repository === 'string') return repository.replace(/^git\+/, '')
  if (repository && typeof repository.url === 'string') return repository.url.replace(/^git\+/, '')
  return typeof homepage === 'string' ? homepage : ''
}

function escapeCell(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ')
}
