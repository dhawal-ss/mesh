import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const UNKNOWN_LICENSE = 'UNKNOWN - REVIEW REQUIRED'

const scriptPath = fileURLToPath(import.meta.url)
const scriptDirectory = dirname(scriptPath)

export async function collectJavaScriptPackages(projectRoot, packageLock) {
  if (!packageLock || typeof packageLock !== 'object'
      || !packageLock.packages || typeof packageLock.packages !== 'object'
      || Array.isArray(packageLock.packages)) {
    throw new Error('package-lock.json does not contain a valid packages object.')
  }

  const packages = []
  for (const [relativePath, lockEntry] of Object.entries(packageLock.packages)) {
    if (!relativePath || !relativePath.includes('node_modules/')) continue
    if (!lockEntry || typeof lockEntry !== 'object' || Array.isArray(lockEntry)) {
      throw new Error(`Invalid lockfile metadata for ${relativePath}.`)
    }

    const manifestPath = resolve(projectRoot, relativePath, 'package.json')
    let manifest = null
    try {
      manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
      if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest)) {
        throw new Error('package manifest must contain a JSON object')
      }
    } catch (error) {
      if (error?.code !== 'ENOENT' || lockEntry.optional !== true) {
        throw new Error(`Unable to read dependency metadata at ${manifestPath}: ${error.message}`, { cause: error })
      }
    }

    const lockLicense = normalizeLicense(lockEntry.license ?? lockEntry.licenses)
    const manifestLicense = normalizeLicense(manifest?.license ?? manifest?.licenses)
    const lockSource = normalizeSource(lockEntry.repository, lockEntry.homepage)
      || normalizeSource(lockEntry.resolved)
    const manifestSource = normalizeSource(manifest?.repository, manifest?.homepage)

    packages.push({
      // Lockfile metadata is canonical so a checked-in notice generated on
      // Windows remains byte-identical when Linux installs a different set of
      // optional platform packages. Manifests are fallback metadata only.
      name: lockEntry.name ?? relativePath.split('node_modules/').at(-1),
      version: lockEntry.version ?? manifest?.version ?? 'unknown',
      license: lockLicense !== UNKNOWN_LICENSE ? lockLicense : manifestLicense,
      source: lockSource || manifestSource,
    })
  }
  return packages
}

export function collectRustPackages(cargoMetadata) {
  if (!cargoMetadata || !Array.isArray(cargoMetadata.packages)) {
    throw new Error('Cargo metadata does not contain a valid packages array.')
  }
  return cargoMetadata.packages
    .filter((dependency) => dependency.name !== 'mesh')
    .map((dependency) => ({
      name: dependency.name,
      version: dependency.version,
      license: normalizeLicense(dependency.license),
      source: normalizeSource(dependency.repository, dependency.homepage)
        || normalizeSource(dependency.source),
    }))
}

export function uniqueSorted(packages) {
  return [...new Map(
    packages.map((dependency) => [
      `${dependency.name}\u0000${dependency.version}\u0000${dependency.license}`,
      dependency,
    ]),
  ).values()].sort((left, right) => (
    left.name.localeCompare(right.name) || left.version.localeCompare(right.version)
  ))
}

export function createNoticeDocument(javascriptPackages, rustPackages) {
  const javascript = uniqueSorted(javascriptPackages)
  const rust = uniqueSorted(rustPackages)
  const unknown = [...javascript, ...rust]
    .filter((dependency) => dependency.license.includes('UNKNOWN'))
  const table = (packages) => packages
    .map((dependency) => `| ${escapeCell(dependency.name)} | ${escapeCell(dependency.version)} | ${escapeCell(dependency.license)} | ${escapeCell(dependency.source)} |`)
    .join('\n')

  return {
    document: `# Mesh third-party notices

Generated by \`npm run generate:third-party-notices\` from the locked JavaScript
and Rust dependency graphs. Regenerate this file on every release candidate.
This inventory does not replace review of the referenced license texts, SBOM,
source-offer obligations, trademarks, or platform redistributables.

- JavaScript packages: ${javascript.length}
- Rust packages: ${rust.length}
- Entries requiring license review: ${unknown.length}

Any \`UNKNOWN - REVIEW REQUIRED\` entry is a release blocker. Legal approval of
the exact candidate remains external acceptance evidence and must not be inferred
from this generated inventory.

## JavaScript dependencies

| Package | Version | License | Source |
| --- | --- | --- | --- |
${table(javascript)}

## Rust dependencies

| Package | Version | License | Source |
| --- | --- | --- | --- |
${table(rust)}
`,
    javascript,
    rust,
    unknown,
  }
}

export async function checkNoticeFile(noticesPath, expectedDocument, unknownCount) {
  const errors = []
  let checkedInDocument
  try {
    checkedInDocument = await readFile(noticesPath, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') {
      errors.push('THIRD_PARTY_NOTICES.md is missing. Run npm run generate:third-party-notices.')
    } else {
      throw new Error(`Unable to read THIRD_PARTY_NOTICES.md: ${error.message}`, { cause: error })
    }
  }

  if (checkedInDocument !== undefined && checkedInDocument !== expectedDocument) {
    errors.push('THIRD_PARTY_NOTICES.md is stale. Run npm run generate:third-party-notices and review the result.')
  }
  if (unknownCount > 0) {
    errors.push(`Third-party notice check blocked: ${unknownCount} dependencies have unresolved licenses.`)
  }
  return errors
}

export function normalizeLicense(value) {
  if (typeof value === 'string' && value.trim()) return value.trim()
  if (Array.isArray(value)) {
    const licenses = value.map((entry) => (
      typeof entry === 'string' ? entry : entry?.type
    ))
      .filter((entry) => typeof entry === 'string' && entry.trim())
      .map((entry) => entry.trim())
    const normalized = [...new Set(licenses)].sort((left, right) => left.localeCompare(right))
    if (normalized.length > 0) return normalized.join(' OR ')
  }
  return UNKNOWN_LICENSE
}

export function normalizeSource(repository, homepage = '') {
  if (typeof repository === 'string' && repository.trim()) {
    return repository.trim().replace(/^git\+/, '')
  }
  if (repository && typeof repository.url === 'string' && repository.url.trim()) {
    return repository.url.trim().replace(/^git\+/, '')
  }
  return typeof homepage === 'string' ? homepage.trim() : ''
}

function escapeCell(value) {
  return String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ')
}

export async function main({
  projectRoot = resolve(scriptDirectory, '..'),
  checkOnly = process.argv.includes('--check'),
} = {}) {
  const noticesPath = resolve(projectRoot, 'THIRD_PARTY_NOTICES.md')
  const packageLock = JSON.parse(await readFile(resolve(projectRoot, 'package-lock.json'), 'utf8'))
  const jsPackages = await collectJavaScriptPackages(projectRoot, packageLock)
  const cargoMetadata = JSON.parse(execFileSync('cargo', [
    'metadata',
    '--format-version', '1',
    '--locked',
    '--manifest-path', resolve(projectRoot, 'src-tauri', 'Cargo.toml'),
  ], { cwd: projectRoot, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }))
  const rustPackages = collectRustPackages(cargoMetadata)
  const { document, javascript, rust, unknown } = createNoticeDocument(jsPackages, rustPackages)

  if (checkOnly) {
    const errors = await checkNoticeFile(noticesPath, document, unknown.length)
    for (const error of errors) console.error(error)
    if (errors.length > 0) {
      process.exitCode = 1
    } else {
      console.log(`Third-party notice check passed: ${javascript.length + rust.length} dependency entries are current and resolved.`)
    }
  } else {
    await writeFile(noticesPath, document, 'utf8')
    console.log(`Wrote THIRD_PARTY_NOTICES.md with ${javascript.length + rust.length} entries (${unknown.length} requiring review).`)
  }
}

if (process.argv[1] && resolve(process.argv[1]) === scriptPath) {
  main().catch((error) => {
    console.error(error)
    process.exitCode = 1
  })
}
